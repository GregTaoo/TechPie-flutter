  GeekPayLocalizations get l10n => GeekPayLocalizations.of(this);
}

final class _GeekPayLocalizationsDelegate
    extends LocalizationsDelegate<GeekPayLocalizations> {
  const _GeekPayLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => GeekPayLocalizations.supportedLocales.any(
        (supported) => supported.languageCode == locale.languageCode,
      );

  @override
  Future<GeekPayLocalizations> load(Locale locale) =>
      SynchronousFuture(GeekPayLocalizations(locale));

  @override
  bool shouldReload(_GeekPayLocalizationsDelegate old) => false;
}
