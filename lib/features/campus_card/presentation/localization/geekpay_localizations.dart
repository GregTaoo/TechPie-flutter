  String fullDateTime(DateTime value) {
    final local = value.toLocal();
    String two(int part) => part.toString().padLeft(2, '0');
    final time = '${two(local.hour)}:${two(local.minute)}:${two(local.second)}';
    return switch (_language) {
      'en' => '${two(local.month)}/${two(local.day)}/${local.year} $time',
      'ja' => '${local.year}/${two(local.month)}/${two(local.day)} $time',
      _ => '${local.year}-${two(local.month)}-${two(local.day)} $time',
    };
  }

  String dateRangeDays(DateTime start, DateTime end) {
    String two(int part) => part.toString().padLeft(2, '0');
    return switch (_language) {
      'en' => '${two(start.month)}/${two(start.day)} to '
          '${two(end.month)}/${two(end.day)}',
      'ja' => '${two(start.month)}/${two(start.day)}〜'
          '${two(end.month)}/${two(end.day)}',
      _ => '${start.month}月${start.day}日 至 ${end.month}月${end.day}日',
    };
  }

